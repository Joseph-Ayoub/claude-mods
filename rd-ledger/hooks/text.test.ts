import { describe, expect, test } from 'claude-code/testing'

import { bareObject, basename, cleanBranch, cleanField, scanJoined, compactInt, csvCell, csvLine, findCredentials, findEmails, globMatch, hasOwn, hoursText, isDate, isId, isMonth, isSeg, isSessionId, isWeek, leakScan, money, oneLine, repoKeyOf, repoRef, sha8, shannonEntropy } from './text'

describe('oneLine', () => {
  test('control characters, line breaks and format characters cannot forge lines', async () => {
    expect(oneLine('a\nb\r\nc\x1b[31md e', 100)).toBe('a b c [31md e')
    expect(oneLine('x​‮y\u{E0041}z', 100)).toBe('xyz')
    expect(oneLine('   many    spaces  ', 100)).toBe('many spaces')
    expect(oneLine('abcdef', 3)).toBe('abc')
    expect(oneLine('', 10)).toBe('')
    // NFC: a decomposed e + combining acute becomes one code point (CYB-11).
    expect(oneLine('e\u0301', 10)).toBe('\u00e9')
    expect([...oneLine('e\u0301', 10)].length).toBe(1)
  })
})

describe('ids and shapes', () => {
  test('session ids, ids, dates, months and weeks', async () => {
    expect(isSessionId('11111111-aaaa-4bbb-8ccc-000000000001')).toBe(true)
    expect(isSessionId('../etc/passwd')).toBe(false)
    expect(isSessionId('11111111-aaaa-4bbb-8ccc-00000000000')).toBe(false)
    expect(isId('acme-app-build')).toBe(true)
    expect(isId('-bad')).toBe(false)
    expect(isId('Bad')).toBe(false)
    expect(isId('a'.repeat(65))).toBe(false)
    expect(isId('')).toBe(false)
    expect(isDate('2026-10-12')).toBe(true)
    expect(isDate('2026-13-01')).toBe(false)
    expect(isMonth('2026-10')).toBe(true)
    expect(isWeek('2026-W41')).toBe(true)
    expect(isWeek('2026-W54')).toBe(false)
  })
  test('basename, repoKeyOf, repoRef, segs and globs', async () => {
    expect(basename('/Users/x/claude-skills-lab/')).toBe('claude-skills-lab')
    expect(basename('/')).toBe('')
    expect(repoKeyOf('/Users/x/My Repo#1|2\n', '/Users/x')).toBe('My Repo_1_2')
    expect(repoKeyOf('/Users/x', '/Users/x')).toBe('~')
    expect(repoKeyOf('/Users/x/', '/Users/x/')).toBe('~')
    expect(repoKeyOf('/', null)).toBe('root')
    expect(repoKeyOf('', null)).toBe('root')
    expect(repoRef('shop', 'abcdef012345')).toBe('shop#abcdef012345')
    expect(repoRef('shop', null)).toBe('shop')
    expect(isSeg('m2x1k9')).toBe(true)
    expect(isSeg('A')).toBe(false)
    expect(globMatch('docs/*', 'docs/readme')).toBe(true)
    expect(globMatch('docs/*', 'docsx')).toBe(false)
    expect(globMatch('main', 'main')).toBe(true)
    expect(globMatch('main', 'main2')).toBe(false)
    expect(globMatch('a*b', 'ab')).toBe(false)
    expect(globMatch('', '')).toBe(false)
    expect(globMatch('x'.repeat(101) + '*', 'x'.repeat(200))).toBe(false)
  })
  test('cleanBranch keeps one printable line and drops HEAD', async () => {
    expect(cleanBranch('feat/x\n')).toBe('feat/x')
    expect(cleanBranch('HEAD\n')).toBe(null)
    expect(cleanBranch('')).toBe(null)
    expect(cleanBranch('bad name')).toBe(null)
    expect(cleanBranch('x'.repeat(201))).toBe(null)
  })
})

describe('csv', () => {
  test('formula prefixes are neutralised and quoting is correct', async () => {
    expect(csvCell('=cmd|calc')).toBe("'=cmd|calc")
    expect(csvCell('+1')).toBe("'+1")
    expect(csvCell('-1')).toBe("'-1")
    expect(csvCell('@x')).toBe("'@x")
    expect(csvCell('\tx')).toBe("'\tx")
    expect(csvCell('a,b')).toBe('"a,b"')
    expect(csvCell('say "hi"')).toBe('"say ""hi"""')
    expect(csvCell('line\nbreak')).toBe('line break')
    expect(csvCell(null)).toBe('')
    expect(csvCell(12.5)).toBe('12.5')
    expect(csvLine(['a', 1, null, '=x'])).toBe("a,1,,'=x")
  })
})

describe('leak scan', () => {
  test('every credential shape is named; prose is not', async () => {
    expect(findCredentials('token sk-ant-abcdefghijkl1234')[0]).toBe('anthropic-key')
    expect(findCredentials('sk-abcdefghijklmnopq')).toEqual(['openai-key'])
    expect(findCredentials('ghp_abcdefghijklmnop')).toEqual(['github-token'])
    expect(findCredentials('github_pat_abcdefghijklmnopqrst')).toEqual(['github-pat'])
    expect(findCredentials('xoxb-abcdefghijk')).toEqual(['slack-token'])
    expect(findCredentials('shpat_' + 'a'.repeat(32))).toEqual(['shopify-token'])
    expect(findCredentials('AKIAABCDEFGHIJKLMNOP')).toEqual(['aws-access-key'])
    expect(findCredentials('eyJabcdefgh.ijklmnop')).toEqual(['jwt'])
    expect(findCredentials('-----BEGIN PRIVATE KEY')).toEqual(['pem-block'])
    expect(findCredentials('client_secret=1')).toEqual(['client-secret'])
    expect(findCredentials('Bearer abcdefghijkl')).toEqual(['bearer-token'])
    expect(findCredentials('12-3456789')).toEqual(['ein'])
    expect(findCredentials('a sk-ful sentence with Bearer of news')).toEqual([])
    expect(findCredentials('')).toEqual([])
    expect(findCredentials('sk_live_abcdefghij')).toEqual(['stripe-key'])
    expect(findCredentials('pk_test_abcdefghij')).toEqual(['stripe-key'])
    expect(findCredentials('glpat-abcdefghijklmnop')).toEqual(['gitlab-token'])
    expect(findCredentials('npm_' + 'a'.repeat(36))).toEqual(['npm-token'])
    expect(findCredentials('AIza' + 'b'.repeat(35))).toEqual(['google-api-key'])
  })
  test('cleanField redacts whole values and never a partial; engine ids skip the entropy rule', async () => {
    expect(cleanField('feat/ghp_abcdefghijklmnop-x', 200)).toEqual({ value: '[redacted:github-token]', redacted: true })
    expect(cleanField('plain\nname', 200)).toEqual({ value: 'plain name', redacted: false })
    expect(cleanField(null, 10)).toEqual({ value: null, redacted: false })
    expect(cleanField('   ', 10)).toEqual({ value: null, redacted: false })
    // An invisible character inside an address or a token must not hide it (verifier V2).
    expect(cleanField('me\u200b@realmail.io', 200)).toEqual({ value: '[redacted:email-address]', redacted: true })
    expect(cleanField('ghp_A1b2C3d4\u200bE5f6G7h8I9j0K1l2', 200)).toEqual({ value: '[redacted:github-token]', redacted: true })
    expect(cleanField('me\u00ad@realmail.io', 200).redacted).toBe(true)
    expect(cleanField('fine\u200bname', 200)).toEqual({ value: 'finename', redacted: false })
    expect(scanJoined('me\u200b@realmail.io')).toBe('email-address')
    for (const ch of ['\u034f', '\ufe0f', '\u115f', '\u1160', '\u3164', '\uffa0', '\u2800', '\u180e']) expect([ch, cleanField(`me${ch}@realmail.io`, 200).redacted]).toEqual([ch, true])
    expect(cleanField('me\uff20realmail.io', 200).redacted).toBe(true)
    for (const ch of ['\u180b', '\u180d', '\u{e0100}', '\u{e01ef}', '\u00a0', ' ']) expect([ch, cleanField(`me${ch}@realmail.io`, 200).redacted]).toEqual([ch, true])
    expect(cleanField('plain words with a space', 200).redacted).toBe(false)
    expect(cleanField('ghp_A1b2C3d4\ufe0fE5f6G7h8I9j0K1l2', 200).redacted).toBe(true)
    const opaque = 'K8xQ2mZp9VbN4rT7wY1cH6jL3sD5fG0aB'
    expect(cleanField(opaque, 80).redacted).toBe(true)
    expect(cleanField(opaque, 80, { isEngineId: true })).toEqual({ value: opaque, redacted: false })
  })
  test('bareObject makes prototype names ordinary keys', async () => {
    const o = bareObject<number>({ a: 1 })
    o['__proto__'] = 2
    o['constructor'] = 3
    expect(hasOwn(o, '__proto__')).toBe(true)
    expect(o['constructor']).toBe(3)
    expect(hasOwn(o, 'toString')).toBe(false)
    expect(Object.getPrototypeOf(o)).toBe(null)
  })
  test('emails are PII unless structurally exempt', async () => {
    expect(findEmails('mail me at joe@acme.io now')).toEqual(['joe@acme.io'])
    expect(findEmails('285628029+Joseph-Ayoub@users.noreply.github.com')).toEqual([])
    expect(findEmails('noreply@anthropic.com')).toEqual([])
    expect(findEmails('a@example.com b@x.test')).toEqual([])
    expect(leakScan('x joe@acme.io')).toBe('email-address')
  })
  test('high-entropy opaque tokens are caught; hex digests, CamelCase and kebab prose are not', async () => {
    expect(leakScan('K8xQ2mZp9VbN4rT7wY1cH6jL3sD5fG0aB')).toBe('high-entropy')
    expect(leakScan('0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef')).toBe(null)
    expect(leakScan('FixtureAppSchedulerCoordinatorFactoryBuilder')).toBe(null)
    expect(leakScan('R30-design-review-choosing-alternatives-and-more')).toBe(null)
    expect(shannonEntropy('')).toBe(0)
    expect(shannonEntropy('aaaa')).toBe(0)
  })
})

describe('format', () => {
  test('sha8 is stable, money and hours format', async () => {
    expect(sha8('union-v2|1800|60|14400')).toBe(sha8('union-v2|1800|60|14400'))
    expect(sha8('a')).not.toBe(sha8('b'))
    expect(sha8('x')).toMatch(/^[0-9a-f]{8}$/)
    expect(money(12.345)).toBe('$12.35')
    expect(money(null)).toBe('--')
    expect(hoursText(5400)).toBe('1.50 h')
    expect(compactInt(1234567)).toBe('1.2M')
    expect(compactInt(12345)).toBe('12.3k')
    expect(compactInt(999)).toBe('999')
  })
})
